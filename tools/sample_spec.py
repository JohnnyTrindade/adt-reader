# Extra scenario: deleted records (ADT keeps them until PACK)
DELETED_SQL = """
CREATE TABLE t_deleted (id INTEGER, v CHAR(10));
INSERT INTO t_deleted VALUES (1, 'keep');
INSERT INTO t_deleted VALUES (2, 'delete me');
INSERT INTO t_deleted VALUES (3, 'keep');
DELETE FROM t_deleted WHERE id = 2;
""".strip()


def build_sql() -> str:
    out = [
        "-- adt-reader synthetic samples",
        "-- Generated by tools/sample_spec.py. Do not edit by hand.",
        "--",
        "-- How to run: see samples/README.md. Run in a FREE TABLE connection",
        "-- (table type ADT) pointing at an empty folder. Each table is",
        "-- independent: if one statement fails, note the error and continue.",
        "",
    ]
    for name, sqltype, rows, note in TABLES:
        out.append(f"-- {name}: {sqltype}" + (f"  ({note})" if note else ""))
        out.append(f"CREATE TABLE {name} (id INTEGER, v {sqltype});")
        for i, (lit, _) in enumerate(rows, 1):
            if lit == "DEFAULT":
                out.append(f"INSERT INTO {name} (id) VALUES ({i});")
            else:
                out.append(f"INSERT INTO {name} (id, v) VALUES ({i}, {lit});")
        out.append("")
    out.append("-- t_deleted: one deleted record (do NOT pack the table)")
    out.append(DELETED_SQL)
    out.append("")
    return "\n".join(out)


def build_expected() -> dict[str, dict]:
    exp = {}
    for name, sqltype, rows, note in TABLES:
        exp[name] = {
            "sql_type": sqltype,
            "note": note,
            "rows": [{"id": i, "v": v} for i, (_, v) in enumerate(rows, 1)],
        }
    exp["t_deleted"] = {
        "sql_type": "CHAR(10)",
        "note": "record id=2 is deleted; reader must skip it by default",
        "rows": [{"id": 1, "v": "keep"}, {"id": 3, "v": "keep"}],
        "deleted_ids": [2],
    }
    return exp


def main() -> None:
    samples = ROOT / "samples"
    (samples / "expected").mkdir(parents=True, exist_ok=True)
    (samples / "generate_samples.sql").write_text(build_sql(), encoding="utf-8")
    for name, data in build_expected().items():
        (samples / "expected" / f"{name}.json").write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(TABLES) + 1} tables to {samples}")


if __name__ == "__main__":
    main()
