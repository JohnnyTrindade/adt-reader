"""Checks every contributed sample in samples/ against samples/expected/.

A sample is samples/<table>.adt (any case) with samples/expected/<table>.json
generated by tools/sample_spec.py. Tables without a file are skipped, so this
test is a no-op until samples arrive.
"""

import json
import math
from pathlib import Path

import pytest

from adtreader import ADTTable
from adtreader.cli import _jsonable

ROOT = Path(__file__).resolve().parent.parent
EXPECTED = sorted((ROOT / "samples" / "expected").glob("*.json"))


def _find_adt(name: str) -> Path | None:
    for p in (ROOT / "samples").glob("*"):
        if p.suffix.lower() == ".adt" and p.stem.lower() == name.lower():
            return p
    return None


def _same(got, want) -> bool:
    if want == "?":  # engine-generated value, not checked
        return True
    if isinstance(want, float) and isinstance(got, float):
        return math.isclose(got, want, rel_tol=1e-12)
    return got == want


@pytest.mark.parametrize("exp_path", EXPECTED, ids=lambda p: p.stem)
def test_sample(exp_path):
    adt = _find_adt(exp_path.stem)
    if adt is None:
        pytest.skip(f"no sample file for {exp_path.stem} yet")
    exp = json.loads(exp_path.read_text(encoding="utf-8"))
    with ADTTable(adt) as t:
        rows = [{k.lower(): _jsonable(v) for k, v in r.items()} for r in t]
        if "deleted_ids" in exp:
            deleted = [t.record(i)["id"] for i in range(len(t)) if t.is_deleted(i)]
            assert sorted(deleted) == sorted(exp["deleted_ids"])
    assert len(rows) == len(exp["rows"]), f"row count for {exp_path.stem}"
    for got, want in zip(sorted(rows, key=lambda r: r["id"]), exp["rows"]):
        assert got["id"] == want["id"]
        assert _same(got["v"], want["v"]), f"id={want['id']}: got {got['v']!r}, want {want['v']!r}"
